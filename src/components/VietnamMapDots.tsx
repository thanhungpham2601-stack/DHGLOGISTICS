interface VietnamMapDotsProps {
  className?: string;
  markerPoint?: { x: number; y: number };
  markerClassName?: string;
}

/** Dotted Vietnam silhouette (mainland + major islands), optionally highlighting one point (e.g. an office location). */
export function VietnamMapDots({ className, markerPoint, markerClassName = 'text-[#7fd4ff]' }: VietnamMapDotsProps) {
  return (
    <svg
      className={className}
      width="100%"
      height="100%"
      viewBox={`0 0 ${VIETNAM_MAP_COLS} ${VIETNAM_MAP_ROWS}`}
      preserveAspectRatio="xMidYMid meet"
      aria-hidden="true"
    >
      {DOTS.map(([x, y], i) => (
        <circle key={i} cx={x} cy={y} r="0.42" fill="currentColor" />
      ))}
      {ISLAND_LABELS.map((label) => (
        <text
          key={label.text}
          x={label.x}
          y={label.y}
          textAnchor="middle"
          fontSize="2.1"
          fontWeight="700"
          letterSpacing="0.03"
          fill="currentColor"
          opacity="0.85"
        >
          {label.text}
        </text>
      ))}
      {markerPoint && (
        <g className={markerClassName}>
          <circle cx={markerPoint.x} cy={markerPoint.y} r="1.8" fill="currentColor" opacity="0.35" className="animate-ping" />
          <circle cx={markerPoint.x} cy={markerPoint.y} r="1" fill="currentColor" />
          <circle cx={markerPoint.x} cy={markerPoint.y} r="1" fill="none" stroke="white" strokeOpacity="0.7" strokeWidth="0.28" />
        </g>
      )}
    </svg>
  );
}
